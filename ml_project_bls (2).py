"""## Box Least Squares (BLS) transit search"""

bls_lc = flat_lc.remove_nans()

# Adjust minimum period to 0.61 days so it is strictly greater than the maximum duration (0.6 days)
# Increase resolution to 100,000 points for a much finer period search
periods = np.exp(np.linspace(np.log(0.61), np.log(300), 100000))

# Keep the recommended comprehensive list of durations (up to 0.6 days)
durations = np.array([0.05, 0.1, 0.15, 0.2, 0.25, 0.3, 0.4, 0.5, 0.52, 0.55, 0.6])

# Run BLS
bls = bls_lc.to_periodogram(method='bls', period=periods, duration=durations)

bls.plot()
plt.title("BLS Periodogram - Kepler-69")
plt.xlabel("Orbital Period (Days)")
plt.ylabel("BLS Power")
plt.show()

best_period = bls.period_at_max_power
t0 = bls.transit_time_at_max_power
dur = bls.duration_at_max_power
print("Period:", best_period)
print("T0:", t0)
print("Duration:", dur)
print("Depth:", bls.depth_at_max_power)
print("Max power:", bls.max_power)

folded = bls_lc.fold(period=best_period, epoch_time=t0)

fig, ax = plt.subplots(1, 2, figsize=(14, 5))
folded.scatter(ax=ax[0], s=2, alpha=0.3)
ax[0].set_title(f"Folded at P = {best_period:.4f}")
folded.bin(time_bin_size=0.02).scatter(ax=ax[1], s=8)
ax[1].set_xlim(-0.5, 0.5)
ax[1].set_title("Zoom on transit (binned)")
plt.show()

# Mask first signal slightly wider (1.5x) to remove transit edges
mask = bls.get_transit_mask(period=best_period, transit_time=t0, duration=dur * 1.5)
masked_lc = bls_lc[~mask]

# Search for the second signal
bls2 = masked_lc.to_periodogram(method='bls', period=periods, duration=durations)
bls2.plot()
plt.title("BLS after masking first signal")
plt.xlabel("Orbital Period (Days)")
plt.ylabel("BLS Power")
plt.show()

print("Second period:", bls2.period_at_max_power)
print("Depth:", bls2.depth_at_max_power)

